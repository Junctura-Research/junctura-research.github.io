"""Pre-render step: build the Intersection pages and lists from _registry.yml.

Reads the front matter of every published document in research/, checks each
against the registry, and writes:

  intersections/<id>.qmd               one page per intersection that has a
                                       published document: image, description,
                                       one section per Junction (Report first,
                                       then Notes, newest first), corrections
  _generated/home-intersections.md     the intersection list on the home page
  _generated/corrections-table.md      the table on the site-wide Corrections page
  _generated/junctions.json            Junction -> Intersection, for filters/doc-meta.lua

The build stops (exit 1) if a document has no junction, names a Junction that is
not in the registry, or has an unknown document-type, or if a correction names
an unknown document. Needs PyYAML.
"""

import datetime as dt
import html
import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
TYPE_LABELS = {
    "intersection-report": "Intersection Report",
    "report-update": "Report Update",
    "research-note": "Research Note",
}
TYPE_ORDER = {"intersection-report": 0, "report-update": 1, "research-note": 2}
MONTHS = ["January", "February", "March", "April", "May", "June", "July",
          "August", "September", "October", "November", "December"]
GENERATED_NOTE = "<!-- Generated by scripts/build_pages.py from _registry.yml. Do not edit. -->\n"


def fmt_date(d) -> str:
    if isinstance(d, str):
        d = dt.date.fromisoformat(d[:10])
    return f"{d.day} {MONTHS[d.month - 1]} {d.year}"


def front_matter(path: Path) -> dict:
    text = path.read_text(encoding="utf-8")
    if not text.startswith("---"):
        return {}
    end = text.index("\n---", 3)
    return yaml.safe_load(text[3:end]) or {}


def esc(s) -> str:
    return html.escape(str(s), quote=True)


def doc_item(doc: dict, prefix: str) -> str:
    """One entry in a document list, matching the home page's listing markup."""
    url = f"{prefix}research/{doc['slug']}.html"
    pdf = f"{prefix}research/{doc['slug']}.pdf"
    meta = [TYPE_LABELS[doc["document-type"]]]
    if doc.get("as-of"):
        meta.append("Evidence as of " + fmt_date(doc["as-of"]))
    if doc.get("date-modified") and str(doc["date-modified"]) != str(doc.get("date")):
        meta.append("Updated " + fmt_date(doc["date-modified"]))
    parts = [
        '<li class="doc-item">',
        f'<p class="doc-type">{esc(" · ".join(meta))}</p>',
        f'<h3 class="doc-title"><a href="{url}">{esc(doc["title"])}</a></h3>',
    ]
    if doc.get("description"):
        parts.append(f'<p class="doc-description">{esc(doc["description"])}</p>')
    parts.append(f'<p class="doc-links"><a href="{url}">Read online</a> · <a href="{pdf}">PDF</a></p>')
    parts.append("</li>")
    return "\n".join(parts)


def corrections_table(rows: list, docs: dict, prefix: str) -> str:
    out = ["| Date found | Document | Error | Fix |", "| --- | --- | --- | --- |"]
    if not rows:
        out.append("| — | — | No corrections to date. | — |")
    for c in rows:
        d = docs[c["document"]]
        link = f"[{d['title']}]({prefix}research/{d['slug']}.html)"
        out.append(f"| {fmt_date(c['date-found'])} | {link} | {c['error']} | {c['fix']} |")
    return "\n".join(out) + "\n"


def main() -> int:
    registry = yaml.safe_load((ROOT / "_registry.yml").read_text(encoding="utf-8"))
    intersections = registry.get("intersections") or {}
    junctions = registry.get("junctions") or {}
    corrections = (yaml.safe_load((ROOT / "_corrections.yml").read_text(encoding="utf-8")) or {}).get("corrections") or []
    errors = []

    for jid, j in junctions.items():
        if j.get("intersection") not in intersections:
            errors.append(f"_registry.yml: junction {jid} names unknown intersection {j.get('intersection')!r}")

    docs = {}
    for path in sorted((ROOT / "research").glob("*.qmd")):
        fm = front_matter(path)
        slug = path.stem
        jid = fm.get("junction")
        dtype = fm.get("document-type")
        if not jid:
            errors.append(f"research/{path.name}: no junction in front matter")
        elif jid not in junctions:
            errors.append(f"research/{path.name}: junction {jid!r} is not in _registry.yml")
        if dtype not in TYPE_LABELS:
            errors.append(f"research/{path.name}: unknown document-type {dtype!r}")
        docs[slug] = {**fm, "slug": slug}

    for c in corrections:
        if c.get("document") not in docs:
            errors.append(f"_corrections.yml: unknown document {c.get('document')!r}")

    if errors:
        for e in errors:
            print("build_pages:", e, file=sys.stderr)
        return 1

    # Group documents: intersection -> junction -> docs
    by_int: dict = {}
    for d in docs.values():
        j = junctions[d["junction"]]
        by_int.setdefault(j["intersection"], {}).setdefault(d["junction"], []).append(d)

    def sort_docs(lst):
        return sorted(lst, key=lambda d: (TYPE_ORDER[d["document-type"]], -dt.date.fromisoformat(str(d.get("date-modified") or d.get("date"))[:10]).toordinal()))

    out_dir = ROOT / "intersections"
    out_dir.mkdir(exist_ok=True)
    for old in out_dir.glob("*.qmd"):
        old.unlink()
    gen = ROOT / "_generated"
    gen.mkdir(exist_ok=True)

    home = [GENERATED_NOTE, '<ul class="intersection-list list-unstyled">']
    # Intersections in registry order, only those with documents
    for iid, inter in intersections.items():
        if iid not in by_int:
            continue
        img = inter["image"]
        desc = inter.get("description", "")
        lines = [
            "---",
            f"title: {json.dumps(inter['title'], ensure_ascii=False)}",
            f"description: {json.dumps(desc, ensure_ascii=False)}",
            f"image: ../images/intersections/{img}-og.jpg",
            "toc: false",
            "---",
            "",
            GENERATED_NOTE,
            "```{=html}",
            f'<img class="intersection-banner" src="../images/intersections/{img}-banner.jpg" '
            f'width="1400" height="700" alt="{esc(inter["image-alt"])}">',
            "```",
            "",
        ]
        int_docs = []
        for jid, j in junctions.items():
            if jid not in by_int[iid]:
                continue
            jd = sort_docs(by_int[iid][jid])
            int_docs += jd
            lines += [f"## {j['title']} {{#{jid}}}", ""]
            if j.get("description"):
                lines += [j["description"], ""]
            if j.get("last-reviewed"):
                lines += [f"[Last reviewed {fmt_date(j['last-reviewed'])}]{{.last-reviewed}}", ""]
            lines += ["```{=html}", '<ul class="doc-list list-unstyled">']
            lines += [doc_item(d, "../") for d in jd]
            lines += ["</ul>", "```", ""]
        int_slugs = {d["slug"] for d in int_docs}
        rows = [c for c in corrections if c["document"] in int_slugs]
        lines += [f"## Corrections in {inter['title']} {{#corrections}}", "",
                  "Every error found in this intersection's published documents, the date it was found and the fix. "
                  "The [site-wide list](../corrections.qmd) covers all intersections.", "",
                  corrections_table(rows, docs, "../")]
        (out_dir / f"{iid}.qmd").write_text("\n".join(lines), encoding="utf-8")

        counts = {}
        for d in int_docs:
            counts[d["document-type"]] = counts.get(d["document-type"], 0) + 1
        count_text = " · ".join(
            f"{n} {TYPE_LABELS[t]}{'s' if n > 1 else ''}" for t, n in sorted(counts.items(), key=lambda kv: TYPE_ORDER[kv[0]]))
        jnames = ", ".join(junctions[j]["title"] for j in junctions if j in by_int[iid])
        home.append("\n".join([
            '<li class="intersection-item">',
            f'<a class="intersection-thumb" href="intersections/{iid}.html">'
            f'<img src="images/intersections/{img}-thumb.jpg" width="120" height="60" alt="{esc(inter["image-alt"])}" loading="lazy"></a>',
            '<div class="intersection-text">',
            f'<h3 class="intersection-title"><a href="intersections/{iid}.html">{esc(inter["title"])}</a></h3>',
            f'<p class="intersection-description">{esc(desc)}</p>',
            f'<p class="intersection-meta">{esc(jnames)} · {esc(count_text)}</p>',
            "</div>",
            "</li>",
        ]))
    home.append("</ul>")
    (gen / "home-intersections.md").write_text("```{=html}\n" + "\n".join(home[1:]) + "\n```\n", encoding="utf-8")
    (gen / "corrections-table.md").write_text(corrections_table(corrections, docs, ""), encoding="utf-8")
    (gen / "junctions.json").write_text(json.dumps({
        jid: {"title": j["title"], "intersection": j["intersection"],
              "intersection-title": intersections[j["intersection"]]["title"],
              "image": intersections[j["intersection"]]["image"]}
        for jid, j in junctions.items()}, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"build_pages: {len(docs)} documents, {len(by_int)} intersection page(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
